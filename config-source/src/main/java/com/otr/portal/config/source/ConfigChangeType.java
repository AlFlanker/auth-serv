package com.otr.portal.config.source;

/**
 * Тип изменения записи в источнике данных.
 * Нейтрален к хранилищу (для ETCD маппится из {@code WatchEvent.EventType}).
 *
 * @author alexraspopin
 */
public enum ConfigChangeType {

    /**
     * Значение создано или обновлено.
     */
    PUT,

    /**
     * Значение удалено.
     */
    DELETE,

    /**
     * Точка синхронизации watch-потока: все изменения, произошедшие после этого события,
     * гарантированно будут доставлены потоком. Эмитится первым событием источниками,
     * умеющими воспроизводить историю с зафиксированного момента (например, ETCD с ревизиями).
     * Прикладного изменения данных не несёт ({@code value == null}).
     */
    SYNC
}
